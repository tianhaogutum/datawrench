"""Pure, escaped recipe rendering; never evaluate input SQL, Python or Jinja."""
from __future__ import annotations

import re
import sqlglot
import yaml

from .core import Inference, identifier, literal
from .csvio import SeedtypesError, validate_delimiter

ADAPTERS = ('duckdb', 'postgres', 'snowflake', 'bigquery', 'redshift', 'databricks')


def adapter_type(dtype: str, adapter: str) -> str:
    if adapter not in ADAPTERS:
        raise SeedtypesError('unknown adapter; supported: ' + ', '.join(ADAPTERS))
    # DATETIME is Snowflake's documented synonym for TIMESTAMP_NTZ. The pinned
    # SQLGlot renders DuckDB TIMESTAMP as the undocumented TIMESTAMPNTZ spelling.
    if adapter == 'snowflake' and dtype == 'TIMESTAMP':
        return sqlglot.exp.DataType.build('DATETIME', dialect='snowflake').sql(dialect='snowflake').lower()
    # BigQuery NUMERIC has a maximum scale of 9; higher scales require BIGNUMERIC.
    if adapter == 'bigquery' and dtype.startswith('DECIMAL'):
        precision, scale = map(int, re.findall(r'\d+', dtype))
        dtype = f'{"BIGNUMERIC" if scale > 9 or precision - scale > 29 else "NUMERIC"}({precision},{scale})'
        return sqlglot.exp.DataType.build(dtype, dialect='bigquery').sql(dialect='bigquery').lower()
    return sqlglot.exp.DataType.build(dtype, dialect='duckdb').sql(dialect=adapter).lower()


def duckdb_sql(result: Inference) -> str:
    # DuckDB 1.4.2 rejects a nullstr containing the selected delimiter, even
    # for quoted fields. Decode as strings and apply that null policy before
    # casting instead, so the generated recipe still accepts the same fields.
    project_nulls = any(result.delimiter in token for token in result.null_tokens)
    columns = ', '.join(f'{literal(col.name)}: {literal("VARCHAR" if project_nulls else col.type)}'
                        for col in result.columns)
    tokens = ('[' + ', '.join(literal(t) for t in result.null_tokens) + ']'
              if result.null_tokens and not project_nulls else 'chr(0)')
    projection = '*'
    if project_nulls:
        null_values = ', '.join(literal(t) for t in result.null_tokens)
        projection = ', '.join(
            f'CAST(CASE WHEN {identifier(col.name)} IN ({null_values}) THEN NULL '
            f'ELSE {identifier(col.name)} END AS {col.type}) AS {identifier(col.name)}'
            for col in result.columns)
    return (f'SELECT {projection} FROM read_csv({literal(result.path)},\n'
            f'    header = true, auto_detect = false, delim = {literal(result.delimiter)}, quote = \'"\', escape = \'"\',\n'
            f'    columns = {{{columns}}}, nullstr = {tokens},\n'
            f'    strict_mode = true, parallel = false, max_line_size = 9000000, buffer_size = 18000000);\n')


def polars_code(result: Inference) -> str:
    dtype_names = {'VARCHAR': 'pl.String', 'BIGINT': 'pl.Int64', 'BOOLEAN': 'pl.Boolean',
                   'DATE': 'pl.Date', 'TIMESTAMP': 'pl.String'}
    overrides = []
    conversions = []
    for col in result.columns:
        if col.type.startswith('DECIMAL'):
            precision, scale = map(int, re.findall(r'\d+', col.type))
            # Polars' CSV reader does not accept Decimal directly for every lexical
            # boundary (notably precision 38); parse strings explicitly, strictly.
            dtype = 'pl.String'
            conversions.append(f'pl.col({col.name!r}).cast(pl.Decimal({precision}, {scale}), strict=True)')
        else:
            dtype = dtype_names[col.type]
        overrides.append(f'{col.name!r}: {dtype}')
        if col.type == 'TIMESTAMP':
            conversions.append(f'pl.col({col.name!r}).str.strptime(pl.Datetime("us"), '
                               'format="%Y-%m-%d %H:%M:%S%.f", strict=True)')
    code = ('# Generated by datawrench seedtypes; review and rerun inference when the CSV changes.\n'
            'import polars as pl\n\n'
            f'schema_overrides = {{{", ".join(overrides)}}}\n'
            f'df = pl.read_csv({result.path!r}, schema_overrides=schema_overrides,\n'
            f'    null_values={result.null_tokens!r}, missing_utf8_is_empty_string={"" not in result.null_tokens},\n'
            f'    separator={result.delimiter!r}, quote_char=\'"\', glob=False, n_threads=1)\n')
    if conversions:
        code += 'df = df.with_columns(\n    ' + ',\n    '.join(conversions) + '\n)\n'
    code += ('\n# Canonical lexical projection, for equality checks against decoded CSV fields.\n'
             '# TIMESTAMP uses DuckDB\'s microsecond spelling (no trailing fractional zeros).\n')
    renders = []
    for col in result.columns:
        expr = f'pl.col({col.name!r})'
        if col.type == 'TIMESTAMP':
            expr += '.dt.strftime("%Y-%m-%d %H:%M:%S%.6f").str.replace(r"(\\.\\d*?)0+$", "$1").str.strip_chars_end(".")'
        else:
            expr += '.cast(pl.String)'
        renders.append(expr)
    return code + 'rendered = df.select(\n    ' + ',\n    '.join(renders) + '\n)\n'


def emit(results: list[Inference], target: str, adapter: str = 'duckdb') -> str:
    import json
    if target == 'json':
        return json.dumps([result.json() for result in results], ensure_ascii=False, indent=2) + '\n'
    if any(not result.columns for result in results):
        raise SeedtypesError('cannot emit a reader or dbt seed for an empty file without a header')
    if target == 'dbt':
        from pathlib import Path
        for result in results:
            validate_delimiter(result.delimiter)
            if Path(result.path).suffix.lower() != '.csv':
                raise SeedtypesError('dbt seeds require .csv filenames; copy TSV input to a .csv file '
                                     'and select --delimiter tab explicitly')
        names = [Path(result.path).stem for result in results]
        if len(set(names)) != len(names):
            raise SeedtypesError('dbt seed names must be unique across input directories')
        if any(result.null_tokens for result in results):
            raise SeedtypesError('dbt emit cannot encode custom null tokens; use DuckDB or Polars output')
        return yaml.safe_dump({'version': 2, 'seeds': [
            {'name': name, 'config': {'delimiter': result.delimiter,
                                    'column_types': {col.name: adapter_type(col.type, adapter)
                                                      for col in result.columns}}}
            for name, result in zip(names, results, strict=True)
        ]}, sort_keys=False, allow_unicode=True)
    if target == 'duckdb':
        return '\n'.join(duckdb_sql(result) for result in results)
    if target == 'polars':
        if len(results) != 1:
            raise SeedtypesError('Polars output accepts exactly one CSV file')
        return polars_code(results[0])
    raise SeedtypesError(f'unknown target: {target}')
